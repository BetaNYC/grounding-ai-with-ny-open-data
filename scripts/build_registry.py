def explorer_href(region: str) -> str:
    # A raw .html link, not a .md one: jekyll-relative-links rewrites `x.md#frag`
    # but not `x.md?query`, so a query-string .md link would 404 on Pages.
    return "../ny-data-portal-registry.html?" + urlencode({"region": region})


def render_portals_index(d: list[dict], today: str) -> str:
    places = [r for r in d if r["page"]]
    by_region = defaultdict(list)
    for r in places:
        by_region[r["region"]].append(r)
    parts = [f"""---
title: "County and city data pages"
status: draft
created: 2026-11-05
updated: {today}
---

# County and city data pages

One page for each county and city in the [New York data directory](../ny-data-portal-registry.md). Each page shows where the place publishes data, how to get it, and an example request. {len(places)} places in {len(by_region)} regions. To search every source, use the [New York data directory](../ny-data-portal-registry.md).
"""]
    for region in sorted(by_region):
        rs = sorted(by_region[region], key=lambda r: str(r["entity"]).lower())
        parts.append(f"## {region}\n")
        for r in rs:
            page = os.path.basename(r["page"])
            parts.append(f"- [{r['entity']}]({page}) — {STATUS_MD.get(r['status'], _e(r['status']))}"
                         f", {_e(r['platform'])}")
        parts.append("")
    parts.append("← [New York data directory](../ny-data-portal-registry.md)\n")
    return "\n".join(parts)


ISSUES_NEW = "https://github.com/BetaNYC/grounding-ai-with-ny-open-data/issues/new"


def correction_href(place: str) -> str:
    """A new-issue link with the data-correction form and the place in the title."""
    return ISSUES_NEW + "?" + urlencode({"template": "data-correction.yml", "title": f"Correction: {place}"})


def _page_title(body: str) -> str:
    m = re.search(r"^# (.+)$", body, re.M)
    return m.group(1).strip() if m else "New York data directory"


def sync_portal_page(text: str, region: str) -> str:
    """Insert or refresh the managed CSS line and footer nav line. Idempotent."""
    m = re.match(r"(---\n.*?\n---\n)(.*)\Z", text, re.S)
    if not m:
        raise ValueError("no front matter")
    head, body = m.groups()
    body = "\n".join(line for line in body.split("\n") if line != CSS_LINE)
    body = CSS_LINE + "\n\n" + body.lstrip("\n")
    nav_prefix = '<a class="rx-place-nav" href="../ny-data-portal-registry.html?'
    lines = [line for line in body.rstrip("\n").split("\n")
             if NAV_MARK not in line and not line.startswith(nav_prefix)]
    while lines and lines[-1] == "":
        lines.pop()
    # Inline HTML for the explorer link (it carries a query string), markdown for
    # the index link so jekyll-relative-links rewrites README.md to wherever it lands.
    nav = (f"{NAV_MARK}\n\n<a class=\"rx-place-nav\" href=\"{html.escape(explorer_href(region))}\">"
           f"See all sources in {html.escape(region)}</a> · [All counties and cities](README.md) · "
           f"<a class=\"rx-place-fix\" href=\"{html.escape(correction_href(_page_title(body)))}\">Report a correction</a>")
    return head + "\n".join(lines).rstrip("\n") + "\n\n" + nav + "\n"


# ---------------------------------------------------------------- driver

def write_or_check(path: str, content: str, check: bool, changed: list[str]) -> None:
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8", newline="") as fh:
            old = fh.read()
    if old == content:
        return
    changed.append(os.path.relpath(path, ROOT))
    if not check:
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(content)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="report changes, write nothing, exit 1 if any")
    ap.add_argument("--date", help="date stamped into the pages (default: JSON 'generated')")
    ap.add_argument("--merge-jsonl", metavar="DIR", help="rebuild the JSON from DIR/*.jsonl first")
    a = ap.parse_args(argv)

    if a.merge_jsonl:
        if not a.date:
            ap.error("--merge-jsonl needs --date")
        raw, problems = merge_jsonl(a.merge_jsonl)
        generated = a.date
    else:
        if not os.path.exists(JSON_PATH):
            sys.exit(f"build_registry: source of truth not found: {JSON_PATH}")
        with open(JSON_PATH, encoding="utf-8") as fh:
            src = json.load(fh)
        raw, problems = src["rows"], []
        generated = a.date or src["generated"]
    rows = normalize(raw)
    problems += problems_in(rows)
    registry_ids, registry_commit = load_registry_ids()
    problems += unknown_registry_ids(rows, registry_ids)
    today = a.date or generated

    changed: list[str] = []
    write_or_check(JSON_PATH, render_json(rows, generated), a.check, changed)
    write_or_check(CSV_PATH, render_csv(rows), a.check, changed)
    write_or_check(MD_PATH, render_md(rows, today), a.check, changed)
    write_or_check(PORTALS_INDEX, render_portals_index(rows, today), a.check, changed)
    for r in rows:
        if not r["page"]:
            continue
        path = os.path.join(RES, r["page"])
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as fh:
            write_or_check(path, sync_portal_page(fh.read(), r["region"]), a.check, changed)

    print(f"build_registry: {len(rows)} rows, {sum(1 for r in rows if r['page'])} place pages, "
          f"{sum(1 for r in rows if r['registry_id'])} linked to ny-gov-web-registry "
          f"(ids pinned at {registry_commit[:7]})")
    for p in problems:
        print(f"build_registry: PROBLEM {p}", file=sys.stderr)
    verb = "would change" if a.check else "wrote"
    print(f"build_registry: {verb} {len(changed)} file(s)" + ("".join(f"\n  {c}" for c in changed)))
    if problems:
        return 2
    return 1 if (a.check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
